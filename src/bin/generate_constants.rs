// Generates the Unity client's GameConstants.cs FROM gameplay_config.toml — so the few
// gameplay constants the client needs BEFORE the server's Welcome (protocol version for the
// Hello handshake, map dimensions, tick rate, base/boosted speed, initial score, turn
// threshold, collision distance) are no longer hand-synced ("change it here too") but
// GENERATED from the single source of truth. Runtime-tunable fairness values travel in
// Welcome; these don't, so codegen is how they stay in lockstep.
//
//   cargo run --bin generate_constants                 # writes $UNITY_ROOT/Assets/Scripts/Sim/GameConstants.cs
//   cargo run --bin generate_constants -- <path>       # explicit output path
//
// scripts/sync_unity_assets.sh runs this for you after a config change. The Hello
// config_hash handshake remains the RUNTIME backstop if a bundle is ever stale.
//
// C# namespace: $CSHARP_NAMESPACE if set, else the one the existing output file already
// declares (regenerating never renames the client's namespace), else `Fairtick.Sim`.

use fairtick::config_shared::{load_config_from_str, GameplayConfig};
use std::path::PathBuf;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let config_bytes = std::fs::read("gameplay_config.toml")?;
    let config = load_config_from_str(std::str::from_utf8(&config_bytes)?)?;

    let out = match std::env::args().nth(1) {
        Some(p) => PathBuf::from(p),
        None => {
            let root = std::env::var("UNITY_ROOT").unwrap_or_else(|_| "../unity".to_string());
            PathBuf::from(root).join("Assets/Scripts/Sim/GameConstants.cs")
        }
    };

    let namespace = std::env::var("CSHARP_NAMESPACE")
        .ok()
        .or_else(|| std::fs::read_to_string(&out).ok().and_then(|existing| existing_namespace(&existing)))
        .unwrap_or_else(|| DEFAULT_NAMESPACE.to_string());
    let cs = render(&config, &namespace);
    if let Some(parent) = out.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(&out, &cs)?;
    println!("Wrote {} ({} bytes) from gameplay_config.toml", out.display(), cs.len());
    Ok(())
}

const DEFAULT_NAMESPACE: &str = "Fairtick.Sim";

/// The namespace a previously generated GameConstants.cs declares, if any.
fn existing_namespace(cs: &str) -> Option<String> {
    cs.lines()
        .find_map(|line| line.trim().strip_prefix("namespace "))
        .map(|ns| ns.trim_end_matches('{').trim().to_string())
        .filter(|ns| !ns.is_empty())
}

/// Render GameConstants.cs from the config. Pure (config → C# source), so it's deterministic
/// and unit-testable. Every number is emitted straight from the toml, so the C# can't drift
/// from the server's values without re-running this generator.
fn render(c: &GameplayConfig, namespace: &str) -> String {
    // f32 → C# float literal. Rust's Display trims a whole float (500.0 → "500"), matching the
    // hand-written file's `500f`; a fractional value keeps its decimals (4.5 → "4.5f").
    fn f(v: f32) -> String {
        format!("{v}f")
    }
    format!(
        "// <auto-generated>
//   GENERATED by `cargo run --bin generate_constants` from gameplay_config.toml.
//   DO NOT EDIT BY HAND — edit gameplay_config.toml (the single source of truth) and re-run
//   the generator (scripts/sync_unity_assets.sh does this). These are the BOOTSTRAP constants
//   the client needs before the server's Welcome (protocol version, map size, tick rate, base
//   speeds); runtime-tunable fairness values travel in Welcome instead. The Hello config_hash
//   handshake is the runtime backstop against a stale bundle.
// </auto-generated>
namespace {namespace}
{{
    /// The minimal config client-side prediction needs before Welcome. Generated.
    public struct SimConfig
    {{
        public float TickRate;
        public float TurnThresholdPx;

        public static SimConfig Default => new SimConfig
        {{
            TickRate = {tick_rate}f,
            TurnThresholdPx = {turn_threshold},
        }};
    }}

    public static class GameConstants
    {{
        // [network] — MUST match network.protocol_version or the Hello handshake is rejected.
        public const uint ProtocolVersion = {protocol_version};
        // Honest Ping cadence — the server derives its ping rate limit from the SAME config
        // value, so tuning it moves both sides together.
        public const int PingIntervalMs = {ping_interval_ms};

        // [room]
        public const int TickRate = {tick_rate};

        // [map]
        public const float MapWidth = {map_width};
        public const float MapHeight = {map_height};
        public const float CellSize = {cell_size};
        public const int GridWidth = {grid_width};
        public const int GridHeight = {grid_height};

        // [gameplay]
        public const float BaseSpeed = {base_speed};
        public const float BoostedSpeed = {boosted_speed};
        public const int InitialScore = {initial_score};
        public const float TurnThresholdPx = {turn_threshold};

        // [collision]
        public const float CollisionDistancePx = {collision};

        public static float TickDt => 1f / TickRate;
    }}
}}
",
        protocol_version = c.network.protocol_version,
        ping_interval_ms = c.network.ping_interval_ms,
        tick_rate = c.room.tick_rate,
        map_width = f(c.map.width),
        map_height = f(c.map.height),
        cell_size = f(c.map.cell_size),
        grid_width = c.map.grid_width,
        grid_height = c.map.grid_height,
        base_speed = f(c.gameplay.base_speed),
        boosted_speed = f(c.gameplay.boosted_speed),
        initial_score = c.gameplay.initial_score,
        turn_threshold = f(c.gameplay.turn_threshold_px),
        collision = f(c.collision.collision_distance_px),
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn cfg() -> GameplayConfig {
        load_config_from_str(include_str!("../../gameplay_config.toml")).unwrap()
    }

    #[test]
    fn generated_constants_derive_from_config_not_hardcoded() {
        let c = cfg();
        let out = render(&c, DEFAULT_NAMESPACE);
        // Every emitted constant must reflect the toml value — proves the generator is wired to
        // the config, so editing the toml and re-running can't silently keep a stale number.
        assert!(out.contains(&format!("ProtocolVersion = {};", c.network.protocol_version)));
        assert!(out.contains(&format!("PingIntervalMs = {};", c.network.ping_interval_ms)));
        assert!(out.contains(&format!("public const int TickRate = {};", c.room.tick_rate)));
        assert!(out.contains(&format!("MapWidth = {}f;", c.map.width)));
        assert!(out.contains(&format!("MapHeight = {}f;", c.map.height)));
        assert!(out.contains(&format!("CellSize = {}f;", c.map.cell_size)));
        assert!(out.contains(&format!("GridWidth = {};", c.map.grid_width)));
        assert!(out.contains(&format!("GridHeight = {};", c.map.grid_height)));
        assert!(out.contains(&format!("BaseSpeed = {}f;", c.gameplay.base_speed)));
        assert!(out.contains(&format!("BoostedSpeed = {}f;", c.gameplay.boosted_speed)));
        assert!(out.contains(&format!("InitialScore = {};", c.gameplay.initial_score)));
        assert!(out.contains(&format!("CollisionDistancePx = {}f;", c.collision.collision_distance_px)));
        assert!(out.contains(&format!("TurnThresholdPx = {}f;", c.gameplay.turn_threshold_px)));
    }

    #[test]
    fn generated_has_expected_csharp_shape() {
        let out = render(&cfg(), DEFAULT_NAMESPACE);
        assert!(out.contains("namespace Fairtick.Sim"));
        assert!(out.contains("public static class GameConstants"));
        assert!(out.contains("public struct SimConfig"));
        assert!(out.contains("auto-generated"), "must carry the do-not-edit marker");
        assert!(out.ends_with("}\n"));
    }

    #[test]
    fn regenerating_keeps_the_existing_namespace() {
        // A client that already consumes `Game.Sim` must not be renamed by a re-run.
        let existing = render(&cfg(), "Game.Sim");
        assert_eq!(existing_namespace(&existing).as_deref(), Some("Game.Sim"));
        assert_eq!(existing_namespace("// no namespace here\n"), None);
    }
}
